// Generates src/components/map/europeShapes.js from Natural Earth (world-atlas 50m).
// Run: node tools/build-map.mjs   (only needed if you change the map framing)
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoConicConformal, geoPath } from 'd3-geo';

const W = 600, H = 420;
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)));
const all = feature(topo, topo.objects.countries).features;
const focus = { '528': 'nl', '276': 'de', '642': 'ro' };

const frame = {
  type: 'Feature',
  geometry: { type: 'MultiPoint', coordinates: [[2.5, 55.6], [30.5, 55.6], [2.5, 43.4], [30.5, 43.4]] },
};
const projection = geoConicConformal().parallels([44, 54]).rotate([-16, 0]).fitExtent([[0, 0], [W, H]], frame);
projection.clipExtent([[-2, -2], [W + 2, H + 2]]);
const path = geoPath(projection);
const round = (d) => d.replace(/(\d+\.\d)\d+/g, '$1');

const countries = [];
for (const f of all) {
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  if (!isFinite(x0) || x1 < 0 || y1 < 0 || x0 > W || y0 > H) continue;
  const d = path(f);
  if (!d) continue;
  countries.push({ id: focus[f.id] || null, d: round(d) });
}
const out = `// AUTO-GENERATED by tools/build-map.mjs — Natural Earth via world-atlas (public domain)
export const MAP_W = ${W};
export const MAP_H = ${H};
export const projectionSettings = ${JSON.stringify({ parallels: [44, 54], rotate: projection.rotate(), scale: projection.scale(), translate: projection.translate() })};
export const countries = ${JSON.stringify(countries)};
`;
writeFileSync(new URL('../src/components/map/europeShapes.js', import.meta.url), out);
console.log('countries', countries.length, 'bytes', out.length);
